const { contextBridge, ipcRenderer } = require("electron");
const { editFieldValue } = require("./utils");

contextBridge.exposeInMainWorld("homePanel", {
  getSettings: () => ipcRenderer.invoke("app:get-settings"),
  saveSettings: (settings) => ipcRenderer.invoke("app:save-settings", settings),
  newEncryptionKey: () => ipcRenderer.invoke("app:new-encryption-key"),
  getSendspinToken: () => ipcRenderer.invoke("app:get-sendspin-token"),
  keyQr: (value) => ipcRenderer.invoke("app:key-qr", value),
  copySecret: (value) => ipcRenderer.invoke("app:copy-secret", value),
  command: (command) => ipcRenderer.invoke("app:command", command),
  setDisplayMode: (mode) => ipcRenderer.invoke("app:set-display-mode", mode),
  quit: () => ipcRenderer.invoke("app:quit"),
  testSound: () => ipcRenderer.invoke("app:test-sound"),
  monitorMic: (on) => ipcRenderer.invoke("app:monitor-mic", on),
  activity: (source) => ipcRenderer.send("app:activity", source),
  setOverlayExpanded: (expanded) => ipcRenderer.send("app:overlay-expanded", expanded),
  setOverlayPopup: (up) => ipcRenderer.send("app:overlay-popup", up),
  setSidePanel: (open) => ipcRenderer.send("app:side-panel", open),
  setKeyboard: (visible) => ipcRenderer.send("app:keyboard", visible),
  setBrightness: (value) => ipcRenderer.invoke("app:set-brightness", value),
  setVolume: (value) => ipcRenderer.invoke("app:set-volume", value),
  voiceOverlay: (full) => ipcRenderer.send("app:voice-overlay", full),
  transport: (command) => ipcRenderer.invoke("app:transport", command),
  keyboardKey: (key) => ipcRenderer.send("app:keyboard-key", key),
  editFieldValue: (field, key) => editFieldValue(field, key),
  onState: (callback) => ipcRenderer.on("app:state", (_event, state) => callback(state)),
  onDeviceState: (callback) => ipcRenderer.on("app:device", (_event, state) => callback(state)),
  onNotification: (callback) => ipcRenderer.on("app:notification", (_event, notice) => callback(notice)),
  onDismissNotification: (callback) => ipcRenderer.on("app:dismiss-notification", callback),
});
